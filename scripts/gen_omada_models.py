#!/usr/bin/env python3
"""Build the Omada AP model table from a controller's model templates.

Input: JSON lines from the controller's ``omada.devicemodeltemplate``
collection (AP records), as written by ``scripts/export-omada-models.sh``.
Output: ``src/open_omada_device_agent/contexts/device/omada_models_data.py``.

Only a few facts per model are kept: bands, spatial streams, transmit power
range and widest channel per radio, Wi-Fi generation and DFS support. Device
identifiers, firmware data and feature lists in the templates are dropped.
See NOTICE.

Usage: python3 scripts/gen_omada_models.py TEMPLATES.jsonl [CONTROLLER_VERSION]
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / (
    "src/open_omada_device_agent/contexts/device/omada_models_data.py"
)

BANDS = {"2.4G": "2g", "5G": "5g", "6G": "6g"}

# supportRadioMode bits (Inferred from the templates: they line up with each
# model's Wi-Fi generation).
MODE_BITS = {
    "2g": {128: 6, 256: 7},
    "5g": {64: 5, 256: 6, 1024: 7},
    "6g": {512: 6, 8: 7},
}

# Channel width bits in channelList cFlag (see device_profile.py).
WIDTH_BITS = ((0x2000000, 320), (0x1000000, 160), (0x800000, 80), (0x60000, 40))

_REGION = re.compile(r"\s*\(([A-Z]{2})\)$")


def _version(value) -> str:
    """A version as the device sent it, as text (some send the number 1)."""
    return "" if value is None else str(value).strip()


def version_key(value: str) -> tuple[int, ...]:
    """Numeric order: "v1.0" < "1.20" < "2.0" < "10.0"."""
    return tuple(int(part) for part in re.findall(r"\d+", value)) or (0,)


def _base_name(model: str) -> tuple[str, str]:
    match = _REGION.search(model)
    return (model[: match.start()], match.group(1)) if match else (model, "")


def _width(band: str, flags: int) -> int:
    for bit, width in WIDTH_BITS:
        if flags & bit and not (band == "2g" and width > 40):
            return width
    return 20


def _generation(dev_cap: dict) -> int:
    gen = 4
    for band, key in (("2g", "supportRadioMode2G"), ("5g", "supportRadioMode5G"),
                      ("6g", "supportRadioMode6G")):
        mode = dev_cap.get(key) or 0
        for bit, value in MODE_BITS[band].items():
            if mode & bit:
                gen = max(gen, value)
    return gen


def reduce_template(record: dict) -> dict | None:
    adopt = json.loads(record["adopt_resp"])
    dev_cap = adopt.get("devCap") or {}
    misc = adopt.get("deviceMisc") or {}
    caps = {cap.get("radioId"): cap for cap in adopt.get("radioCap") or []}
    radios = []
    for info in adopt.get("channelInfo") or []:
        band = BANDS.get(info.get("band"))
        if band is None:
            continue
        flags = 0
        for channel in info.get("channelList") or []:
            flags |= int(channel.get("cFlag") or 0)
        cap = caps.get(info.get("radioId")) or {}
        radios.append({
            "band": band,
            "nss": int(cap.get("mimo") or dev_cap.get(f"mimo{info['band']}") or 1),
            "min_tx": int(cap.get("minPow") or 0),
            "max_tx": int(cap.get("maxPow") or 0),
            "max_width": _width(band, flags),
        })
    if not radios:
        return None
    name, region = _base_name(record["model"])
    info = adopt.get("deviceInfo") or {}
    return {
        "model": name,
        # What a real device of this model sends at adoption.
        "model_version": _version(info.get("modelVersion")),
        "hardware_version": _version(info.get("hardwareVersion")),
        "regions": [region] if region else [],
        "gen": _generation(dev_cap),
        "dfs": bool(misc.get("supportDfs")),
        "radios": radios,
    }


def build(records: list[dict]) -> list[dict]:
    """One row per model name; regional variants are merged into ``regions``."""
    models: dict[str, dict] = {}
    for record in records:
        if record.get("type") != "ap":
            continue
        row = reduce_template(record)
        if row is None:
            continue
        if "(" in row["model"]:
            print(f"warning: unexpected suffix in model name {row['model']!r}", file=sys.stderr)
        have = models.get(row["model"])
        if have is None:
            models[row["model"]] = row
            continue
        have["regions"] = sorted(set(have["regions"]) | set(row["regions"]))
        if version_key(row["model_version"]) > version_key(have["model_version"]):
            row["regions"] = have["regions"]
            models[row["model"]] = row
    return sorted(models.values(), key=lambda row: row["model"])


def render(rows: list[dict], controller_version: str) -> str:
    lines = [
        '"""Omada AP models: a few facts per model, generated by',
        "scripts/gen_omada_models.py from the model templates of Omada Controller",
        f"{controller_version}. Do not edit by hand; see NOTICE.",
        '"""',
        "",
        f"CONTROLLER_VERSION = {controller_version!r}",
        "",
        "MODELS: tuple[dict, ...] = (",
    ]
    lines.extend(f"    {json.dumps(row, sort_keys=True)}," for row in rows)
    lines.append(")")
    return "\n".join(lines).replace(": true", ": True").replace(": false", ": False") + "\n"


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    records = [json.loads(line) for line in Path(argv[1]).read_text().splitlines() if line.strip()]
    version = argv[2] if len(argv) > 2 else "unknown"
    rows = build(records)
    OUTPUT.write_text(render(rows, version))
    print(f"{len(rows)} models written to {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
